@app.websocket("/ws/interview/{session_id}")
async def websocket_interview(websocket: WebSocket, session_id: str):
    """
    Real-time interview session over WebSocket.

    Protocol:
    1. Client connects -> server activates session, sends INTRO + TTS
    2. Client sends answers (text or audio) -> server processes, responds
    3. Loop until interview completes
    4. Server sends final report, closes connection
    """
    await websocket.accept()
    logger.info(f"[WS {session_id}] Client connected")
    orchestrator = None

    try:
        # -- Activate session and get orchestrator -------------------------
        try:
            orchestrator = session_manager.activate_session(session_id)
        except SessionNotFoundError:
            await _ws_send_error(websocket, f"Session not found: {session_id}")
            await websocket.close(code=4004, reason="Session not found")
            return
        except SessionStateError as e:
            await _ws_send_error(websocket, str(e))
            await websocket.close(code=4009, reason="Invalid session state")
            return

        # Build technical prompt for STT accuracy
        plan = orchestrator._plan
        skills = [q.skill for q in plan.questions]
        stt_prompt = build_technical_prompt(skills, plan.job_role)

        # -- INTRO phase ---------------------------------------------------
        logger.info(f"[WS {session_id}] Starting INTRO")
        intro_response = await orchestrator.start()

        await _ws_send_interviewer_message(
            websocket,
            msg_type="intro",
            response=intro_response,
        )

        # Stream TTS for intro
        await _ws_stream_tts(websocket, intro_response.text)

        # -- Session-level timer -------------------------------------------
        duration_limit = getattr(plan, "duration_limit", 1800)
        session_deadline = time.monotonic() + duration_limit

        # -- Main interview loop -------------------------------------------
        while not orchestrator.is_complete:
            # ── Session timeout check ────────────────────────────────────
            remaining = session_deadline - time.monotonic()
            if remaining <= 0:
                logger.info(f"[WS {session_id}] Session time limit reached")
                response = await orchestrator.force_timeout()
                await _ws_send_interviewer_message(websocket, msg_type="close", response=response)
                await _ws_stream_tts(websocket, response.text)
                report = orchestrator.get_report()
                await _save_and_evaluate(session_id, report)
                await websocket.send_json({"type": "complete"})
                break

            # ── Wait for candidate's answer ───────────────────────────────
            try:
                candidate_text = await asyncio.wait_for(
                    _ws_receive_answer(websocket, session_id, stt_prompt),
                    timeout=remaining,
                )
            except asyncio.TimeoutError:
                # Session time limit expired while waiting for candidate
                logger.info(f"[WS {session_id}] Session time limit reached while waiting")
                response = await orchestrator.force_timeout()
                await _ws_send_interviewer_message(websocket, msg_type="close", response=response)
                await _ws_stream_tts(websocket, response.text)
                report = orchestrator.get_report()
                await _save_and_evaluate(session_id, report)
                await websocket.send_json({"type": "complete"})
                logger.info(f"[WS {session_id}] Interview completed (session timeout)")
                break

            # ── End session signal ────────────────────────────────────────
            if candidate_text == "!END_SESSION!":
                logger.info(f"[WS {session_id}] User explicitly ended session.")
                await orchestrator.force_early_close()
                report = orchestrator.get_report()
                await _save_and_evaluate(session_id, report)
                try:
                    await websocket.send_json({"type": "complete"})
                except Exception:
                    pass
                break

            if candidate_text is None:
                break

            logger.info(f"[WS {session_id}] Candidate said: {candidate_text}")

            # ── Clarification check ───────────────────────────────────────
            intent = await orchestrator.get_candidate_intent(candidate_text)
            if intent == "clarification":
                response = await orchestrator.handle_clarification(candidate_text)
                logger.info(f"[WS {session_id}] Clarification detected")
                await _ws_send_interviewer_message(
                    websocket, msg_type="clarification", response=response,
                )
                await _ws_stream_tts(websocket, response.text)
                continue  # wait for the real answer; do NOT advance state
            elif intent == "answer_seeking":
                response = await orchestrator.handle_answer_seeking(candidate_text)
                logger.info(f"[WS {session_id}] Answer seeking detected")
                await _ws_send_interviewer_message(
                    websocket, msg_type="clarification", response=response,
                )
                await _ws_stream_tts(websocket, response.text)
                continue  # wait for the real answer; do NOT advance state
            elif intent == "off_topic":
                response = await orchestrator.handle_off_topic(candidate_text)
                logger.info(f"[WS {session_id}] Off-topic detected")
                await _ws_send_interviewer_message(
                    websocket, msg_type="clarification", response=response,
                )
                await _ws_stream_tts(websocket, response.text)
                continue  # redirect and wait for the real answer; do NOT advance state

            # ── Normal answer processing ──────────────────────────────────
            response = await orchestrator.handle_answer(candidate_text)

            if response.is_complete:
                msg_type = "close"
            elif response.state == "FOLLOWUP":
                msg_type = "followup"
            else:
                msg_type = "question"

            await _ws_send_interviewer_message(
                websocket, msg_type=msg_type, response=response,
            )
            await _ws_stream_tts(websocket, response.text)

            if response.is_complete:
                report = orchestrator.get_report()
                await _save_and_evaluate(session_id, report)
                await websocket.send_json({"type": "complete"})
                logger.info(f"[WS {session_id}] Interview completed")
                break

    except WebSocketDisconnect:
        logger.info(f"[WS {session_id}] Client disconnected")
        if orchestrator and not orchestrator.is_complete:
            logger.info(f"[WS {session_id}] Saving partial data after disconnect.")
            try:
                await orchestrator.force_early_close()
                report = orchestrator.get_report()
                report_storage.save_report(session_id, report)
            except Exception as e:
                logger.error(f"[WS {session_id}] Failed to save partial data: {e}")
    except Exception as exc:
        logger.error(f"[WS {session_id}] Error: {exc}", exc_info=True)
        try:
            await _ws_send_error(websocket, f"Internal error: {str(exc)}")
        except Exception:
            pass
    finally:
        logger.info(f"[WS {session_id}] Session ended")


