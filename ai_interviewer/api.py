@app.post("/api/interview/prepare", response_model=PrepareResponse)
async def prepare_interview(req: PrepareRequest):
    """
    Create an interview session from the Planner's output.

    Called by the .NET backend after it runs the Planner.
    The session_id is generated by .NET and passed here.
    """
    # Check for duplicate session
    try:
        existing = session_manager.get_session_status(req.session_id)
        raise HTTPException(
            status_code=409,
            detail=f"Session {req.session_id} already exists (status: {existing})",
        )
    except SessionNotFoundError:
        pass  # Good — session doesn't exist yet

    # Convert request to plan object
    plan = PlanFromRequest(req)

    # Create the session
    session_id = session_manager.create_session(plan)

    logger.info(
        f"Session prepared | id={session_id} "
        f"candidate={req.candidate_name} "
        f"questions={len(req.questions)}"
    )

    return PrepareResponse(
        session_id=session_id,
        status="pending",
        candidate_name=req.candidate_name,
        total_questions=len(req.questions),
        websocket_url=f"/ws/interview/{session_id}",
    )


@app.get("/api/interview/{session_id}/status", response_model=SessionStatusResponse)
async def get_session_status(session_id: str):
    """Get the current status of an interview session."""
    try:
        info = session_manager.get_session_info(session_id)
        return SessionStatusResponse(**info)
    except SessionNotFoundError:
        raise HTTPException(status_code=404, detail=f"Session not found: {session_id}")


@app.get("/api/interview/{session_id}/transcript", response_model=ReportResponse)
async def get_session_transcript(session_id: str):
    """
    Get the final interview transcript (report).

    Only available after the interview is completed.
    """
    # 1. Try to fetch from hybrid storage (Redis -> RAM)
    report = report_storage.get_report(session_id)
    if report:
        return ReportResponse(
            session_id=session_id,
            status="completed",
            report=report,
        )

    # 2. If not found in storage, check session_manager directly to see if the session exists but isn't completed
    try:
        status = session_manager.get_session_status(session_id)
        if status != "completed":
            raise HTTPException(
                status_code=400,
                detail=f"Interview not completed yet (status: {status})",
            )
        # If it says completed but report wasn't returned, something is wrong
        raise HTTPException(status_code=404, detail="Report data not found.")
    except SessionNotFoundError:
        raise HTTPException(status_code=404, detail=f"Session not found: {session_id}")


@app.delete("/api/interview/{session_id}")
async def delete_session(session_id: str):
    """
    Delete a session and its report.
    """
    # The storage layer deletes from both Redis and RAM
    report_storage.delete_report(session_id)
    return {"status": "deleted", "session_id": session_id}


