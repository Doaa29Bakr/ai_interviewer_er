"""
Interview API
==============

FastAPI application with REST + WebSocket endpoints for the AI Interviewer.

REST Endpoints (called by .NET backend)
----------------------------------------
POST   /api/interview/prepare           — Create session with plan data
GET    /api/interview/{session_id}/status — Check session status
GET    /api/interview/{session_id}/transcript — Get final interview transcript
DELETE /api/interview/{session_id}       — Delete a session
GET    /health                           — Server health check

WebSocket Endpoint (opened by React frontend)
----------------------------------------------
WS     /ws/interview/{session_id}        — Real-time interview session

WebSocket Protocol
------------------
Server -> Client (text frames = JSON):
    { type: "intro",    text: "...", state: "INTRO" }
    { type: "question", text: "...", state: "ASK",      question_index: 1, total_questions: 5 }
    { type: "followup", text: "...", state: "FOLLOWUP", question_index: 1, total_questions: 5 }
    { type: "close",    text: "...", state: "CLOSE" }
    { type: "complete", report: {...} }
    { type: "tts_start" }
    { type: "tts_end" }
    { type: "error",    message: "..." }

Server -> Client (binary frames):
    Raw TTS audio chunks (PCM/WAV, stream between tts_start and tts_end)

Client -> Server (text frames = JSON):
    { type: "answer", text: "..." }          — Pre-transcribed answer
    { type: "answer_audio" }                 — Signals next binary frame is audio

Client -> Server (binary frames):
    Raw audio data for STT (sent after "answer_audio" signal)
"""

