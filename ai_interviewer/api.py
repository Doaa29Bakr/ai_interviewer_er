async def _ws_send_interviewer_message(
    websocket: WebSocket,
    msg_type: str,
    response: Any,
) -> None:
    """Send the interviewer's text response as a JSON message."""
    message = {
        "type": msg_type,
        "text": response.text,
        "state": response.state,
        "question_index": response.question_index,
        "total_questions": response.total_questions,
    }

    if response.evaluation:
        message["evaluation"] = response.evaluation

    if response.followup_triggered:
        message["followup_triggered"] = True

    await websocket.send_json(message)


async def _ws_stream_tts(websocket: WebSocket, text: str) -> None:
    """Stream TTS audio chunks to the client."""
    try:
        # Signal TTS start
        await websocket.send_json({"type": "tts_start"})

        chunk_count = 0
        total_bytes = 0
        start = time.perf_counter()

        async for chunk in synthesize_streaming(text):
            await websocket.send_bytes(chunk)
            chunk_count += 1
            total_bytes += len(chunk)

        elapsed = (time.perf_counter() - start) * 1000

        # Signal TTS end
        await websocket.send_json({"type": "tts_end"})

        logger.debug(
            f"TTS streamed: {chunk_count} chunks, "
            f"{total_bytes:,} bytes, {elapsed:.0f}ms"
        )

    except Exception as exc:
        logger.error(f"TTS streaming error: {exc}")
        await websocket.send_json({
            "type": "tts_end",
            "error": str(exc),
        })


async def _ws_receive_answer(
    websocket: WebSocket,
    session_id: str,
    stt_prompt: str,
) -> Optional[str]:
    """
    Wait for the candidate's answer from the WebSocket.

    Handles two input modes:
    1. Text answer: { type: "answer", text: "..." }
    2. Audio answer: { type: "answer_audio" } followed by binary audio frame

    Returns the transcribed/provided text, or None on error.
    """
    try:
        # Receive the first message (could be text JSON or binary audio)
        message = await websocket.receive()

        # -- Text frame (JSON) --------------------------------------------
        if "text" in message:
            data = json.loads(message["text"])
            msg_type = data.get("type", "")

            if msg_type == "answer":
                # Pre-transcribed text answer
                return data.get("text", "").strip()

            elif msg_type == "end_session":
                return "!END_SESSION!"

            elif msg_type == "answer_audio":
                # Signal that the next frame will be binary audio
                audio_msg = await websocket.receive()
                if "bytes" in audio_msg:
                    return await _transcribe_audio(
                        audio_msg["bytes"], session_id, stt_prompt
                    )
                else:
                    logger.warning(
                        f"[WS {session_id}] Expected binary audio after answer_audio signal"
                    )
                    return None

            else:
                logger.warning(
                    f"[WS {session_id}] Unknown message type: {msg_type}"
                )
                return data.get("text", "").strip() or None

        # -- Binary frame (raw audio) -------------------------------------
        elif "bytes" in message:
            return await _transcribe_audio(
                message["bytes"], session_id, stt_prompt
            )

        return None

    except WebSocketDisconnect:
        raise
    except Exception as exc:
        logger.error(f"[WS {session_id}] Error receiving answer: {exc}")
        return None


async def _transcribe_audio(
    audio_bytes: bytes,
    session_id: str,
    stt_prompt: str,
) -> Optional[str]:
    """Transcribe audio bytes using STT (Groq Whisper)."""
    try:
        logger.info(
            f"[WS {session_id}] Transcribing {len(audio_bytes):,} bytes..."
        )

        # Run STT in a thread pool (it's a sync HTTP call)
        loop = asyncio.get_event_loop()
        result = await loop.run_in_executor(
            None,
            lambda: transcribe(
                audio_bytes=audio_bytes,
                filename="answer.webm",  # Most browsers record in WebM
                prompt=stt_prompt,
            ),
        )

        if result.is_empty:
            logger.warning(f"[WS {session_id}] STT returned empty transcription")
            return "I'm not sure, could you repeat the question?"

        logger.info(
            f"[WS {session_id}] STT: '{result.text[:60]}...' "
            f"({result.duration_ms:.0f}ms)"
        )

        return result.text

    except Exception as exc:
        logger.error(f"[WS {session_id}] STT failed: {exc}")
        return None


async def _ws_send_error(websocket: WebSocket, message: str) -> None:
    """Send an error message to the client."""
    await websocket.send_json({
        "type": "error",
        "message": message,
    })


