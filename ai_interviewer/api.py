class QuestionInput(BaseModel):
    """A single interview question from the Planner."""
    question: str
    golden_answer: str
    skill: str
    rationale: Optional[str] = None
    time_limit_seconds: Optional[int] = None


class PrepareRequest(BaseModel):
    """
    Request body for POST /api/interview/prepare.

    Sent by the .NET backend after running the Planner.
    """
    session_id: str = Field(
        ...,
        description="Unique session ID (GUID generated by .NET backend)",
    )
    candidate_name: str = Field(..., description="Candidate's full name")
    job_role: str = Field(..., description="Target job role")
    level: str = Field(
        "Junior",
        description="Experience level: Junior, Mid, or Senior",
    )
    duration_limit: int = Field(
        1800,
        description="Duration limit of the interview in seconds",
    )
    questions: list[QuestionInput] = Field(
        ...,
        min_length=1,
        description="Interview questions from the Planner",
    )


class PrepareResponse(BaseModel):
    session_id: str
    status: str
    candidate_name: str
    total_questions: int
    websocket_url: str


class SessionStatusResponse(BaseModel):
    session_id: str
    status: str
    candidate_name: str
    job_role: str
    total_questions: int
    created_at: Optional[str] = None
    activated_at: Optional[str] = None
    completed_at: Optional[str] = None
    age_hours: float = 0.0


class ReportResponse(BaseModel):
    session_id: str
    status: str
    report: Optional[dict[str, Any]] = None


# ========================================================================
# InterviewPlan adapter (converts PrepareRequest to plan-like object)
# ========================================================================

class PlanFromRequest:
    """
    Adapts PrepareRequest into the plan object that InterviewOrchestrator expects.

    The orchestrator accesses: plan.session_id, plan.candidate_name,
    plan.job_role, plan.level, plan.questions[].question/golden_answer/skill
    """

    def __init__(self, req: PrepareRequest):
        self.session_id = req.session_id
        self.candidate_name = req.candidate_name
        self.job_role = req.job_role
        self.level = req.level
        self.duration_limit = req.duration_limit
        self.questions = [
            _QuestionAdapter(q) for q in req.questions
        ]


class _QuestionAdapter:
    """Adapts QuestionInput to the attribute-access interface the orchestrator uses."""

    def __init__(self, q: QuestionInput):
        self.question = q.question
        self.golden_answer = q.golden_answer
        self.skill = q.skill


