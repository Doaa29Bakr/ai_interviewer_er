async def _save_and_evaluate(session_id: str, report: dict) -> None:
    """
    Save the interview report and auto-trigger the evaluation pipeline
    in the background so the WebSocket response is not delayed.

    After evaluation completes, the result is pushed to the .NET webhook
    configured via the WEBHOOK_URL key in api_keys.json or environment.
    """
    report_storage.save_report(session_id, report)

    async def _run():
        try:
            logger.info(f"[Evaluator] Auto-triggering evaluation for session {session_id}")
            result = await asyncio.to_thread(run_evaluation, session_id)

            # Merge evaluation result into the stored report
            merged = {**report, "evaluation": result}
            report_storage.save_report(session_id, merged)
            logger.info(
                f"[Evaluator] Evaluation complete for session {session_id} "
                f"— avg_score={result.get('average_score')}"
            )

            # ── Webhook push ─────────────────────────────────────────────
            webhook_url = get_key("WEBHOOK_URL")
            if webhook_url:
                try:
                    async with httpx.AsyncClient(timeout=15.0) as client:
                        response = await client.post(webhook_url, json=result)
                        response.raise_for_status()
                    logger.info(
                        f"[Webhook] Successfully pushed evaluation for session {session_id} "
                        f"→ {webhook_url} (HTTP {response.status_code})"
                    )
                except httpx.HTTPStatusError as exc:
                    logger.error(
                        f"[Webhook] Server rejected payload for session {session_id}: "
                        f"HTTP {exc.response.status_code} — {exc.response.text[:200]}"
                    )
                except httpx.RequestError as exc:
                    logger.error(
                        f"[Webhook] Failed to reach webhook for session {session_id}: {exc}"
                    )
            else:
                logger.warning(
                    f"[Webhook] WEBHOOK_URL not configured — skipping push for session {session_id}. "
                    "Add 'WEBHOOK_URL' to api_keys.json to enable webhook delivery."
                )

        except Exception as exc:
            logger.error(f"[Evaluator] Background evaluation failed for {session_id}: {exc}")

    asyncio.create_task(_run())


